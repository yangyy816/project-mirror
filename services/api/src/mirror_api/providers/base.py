@dataclass(frozen=True)
class FaceLandmark:
    landmark_code: str
    x: float
    y: float
    confidence: float

    def __post_init__(self) -> None:
        _require_opaque_reference(self.landmark_code, field_name="landmark code")
        if not 0.0 <= self.x <= 1.0 or not 0.0 <= self.y <= 1.0:
            raise ValueError("landmark coordinates must be normalized to the image bounds")
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("landmark confidence must be between zero and one")


@dataclass(frozen=True)
class FaceLandmarkSet:
    coordinate_system: Literal["normalized_image_v1"]
    landmarks: tuple[FaceLandmark, ...]

    def __post_init__(self) -> None:
        if self.coordinate_system != "normalized_image_v1":
            raise ValueError("landmark coordinate system is not allowed")
        if not self.landmarks or len(self.landmarks) > MAX_SYNTHETIC_LANDMARKS_PER_FACE:
            raise ValueError("landmark set is outside the allowed cardinality boundary")
        if len({landmark.landmark_code for landmark in self.landmarks}) != len(self.landmarks):
            raise ValueError("landmark codes must be unique within a face")


@dataclass(frozen=True)
class PoseEstimate:
    yaw_degrees: float
    pitch_degrees: float
    roll_degrees: float
    confidence: float

    def __post_init__(self) -> None:
        if any(
            abs(angle) > 180.0
            for angle in (self.yaw_degrees, self.pitch_degrees, self.roll_degrees)
        ):
            raise ValueError("pose angles must be within the closed 180-degree boundary")
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("pose confidence must be between zero and one")


@dataclass(frozen=True)
class GeometryMeasurement:
    measurement_code: str
    value: float
    confidence: float
    measurement_version: str

    def __post_init__(self) -> None:
        _require_opaque_reference(self.measurement_code, field_name="geometry measurement code")
        _require_opaque_reference(
            self.measurement_version, field_name="geometry measurement version"
        )
        if not -10_000.0 <= self.value <= 10_000.0:
            raise ValueError("geometry measurement value is outside the bounded range")
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("geometry measurement confidence must be between zero and one")


@dataclass(frozen=True)
class FaceObservation:
    observation_reference: str
    landmarks: FaceLandmarkSet
    pose: PoseEstimate
    geometry_measurements: tuple[GeometryMeasurement, ...]

    def __post_init__(self) -> None:
        _require_opaque_reference(
            self.observation_reference, field_name="face observation reference"
        )
        if len(self.geometry_measurements) > MAX_SYNTHETIC_GEOMETRY_MEASUREMENTS:
            raise ValueError("geometry measurements exceed the allowed cardinality boundary")
        codes = [measurement.measurement_code for measurement in self.geometry_measurements]
        if len(set(codes)) != len(codes):
            raise ValueError("geometry measurement codes must be unique within a face")


