SYNTHETIC_IMAGE_MEDIA_TYPES = frozenset({"image/jpeg", "image/png", "image/webp"})
MAX_SYNTHETIC_GENERATED_IMAGE_BYTES = 20 * 1024 * 1024
MAX_SYNTHETIC_FACE_OBSERVATIONS = 16
MAX_SYNTHETIC_LANDMARKS_PER_FACE = 512
MAX_SYNTHETIC_GEOMETRY_MEASUREMENTS = 128
MAX_SYNTHETIC_GENERATION_PARAMETERS = 32
MAX_SYNTHETIC_SEED = (1 << 63) - 1
_OPAQUE_REFERENCE = re.compile(r"^[a-z][a-z0-9_-]{2,63}$")


def _require_opaque_reference(value: str, *, field_name: str) -> None:
    """Reject URLs, object keys and provider-specific identifiers at the port boundary."""
    if not _OPAQUE_REFERENCE.fullmatch(value):
        raise ValueError(f"{field_name} must use the opaque first-party reference syntax")


def _require_synthetic_subject(subject_kind: str) -> None:
    if subject_kind != "synthetic":
        raise ValueError("provider contract only accepts synthetic subjects")


@dataclass(frozen=True)
class GeneratedImagePayload:
    """Bounded generated bytes; never a URL, object key, SDK value or raw response."""

    content: bytes
    media_type: Literal["image/jpeg", "image/png", "image/webp"]
    subject_kind: Literal["synthetic"] = "synthetic"

    def __post_init__(self) -> None:
        _require_synthetic_subject(self.subject_kind)
        if type(self.content) is not bytes:
            raise ValueError("generated image content must be immutable bytes")
        if not 0 < len(self.content) <= MAX_SYNTHETIC_GENERATED_IMAGE_BYTES:
            raise ValueError("generated image content is outside the allowed size boundary")
        if self.media_type not in SYNTHETIC_IMAGE_MEDIA_TYPES:
            raise ValueError("generated image media type is not allowed")

    @property
    def byte_size(self) -> int:
        return len(self.content)


@dataclass(frozen=True)
class SyntheticOutputSpecification:
    """Requested bounded image shape and MIME, without a provider-specific option bag."""

    media_type: Literal["image/jpeg", "image/png", "image/webp"]
    width: int
    height: int
    max_byte_size: int

    def __post_init__(self) -> None:
        if self.media_type not in SYNTHETIC_IMAGE_MEDIA_TYPES:
            raise ValueError("synthetic output media type is not allowed")
        if self.width < 1 or self.height < 1 or self.width > 8192 or self.height > 8192:
            raise ValueError("synthetic output dimensions are outside the allowed boundary")
        if self.width * self.height > 40_000_000:
            raise ValueError("synthetic output pixel count is outside the allowed boundary")
        if not 0 < self.max_byte_size <= MAX_SYNTHETIC_GENERATED_IMAGE_BYTES:
            raise ValueError("synthetic output maximum bytes are outside the allowed boundary")


