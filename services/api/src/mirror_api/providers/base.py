@dataclass(frozen=True)
class GenerationParameter:
    """One explicit scalar parameter; free-form strings/JSON cannot cross this port."""

    parameter_key: str
    value: GenerationParameterValue

    def __post_init__(self) -> None:
        _require_opaque_reference(self.parameter_key, field_name="generation parameter key")
        if type(self.value) not in {bool, int, float}:
            raise ValueError("generation parameter value must be a scalar number or boolean")
        if isinstance(self.value, float) and not math.isfinite(self.value):
            raise ValueError("generation parameter value must be finite")


def _validate_generation_parameters(parameters: tuple[GenerationParameter, ...]) -> None:
    if len(parameters) > MAX_SYNTHETIC_GENERATION_PARAMETERS:
        raise ValueError("generation parameters exceed the allowed cardinality boundary")
    keys = [parameter.parameter_key for parameter in parameters]
    if len(set(keys)) != len(keys):
        raise ValueError("generation parameter keys must be unique")


def _validate_seed(seed: int | None, *, field_name: str) -> None:
    if seed is not None and (type(seed) is not int or seed < 0 or seed > MAX_SYNTHETIC_SEED):
        raise ValueError(f"{field_name} must be a bounded non-negative integer or None")


